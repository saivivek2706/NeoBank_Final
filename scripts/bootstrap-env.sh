#!/usr/bin/env bash
# Generates a local .env with FRESH random secrets (RSA signing keypair, AES/HMAC keys, DB passwords,
# first admin credentials). Nothing secret is committed to the repository - run this once per checkout.
#
#   ./scripts/bootstrap-env.sh           # create .env (no-op if it already exists)
#   ./scripts/bootstrap-env.sh --force   # regenerate; DATA ENCRYPTED WITH THE OLD KEYS BECOMES UNREADABLE
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -f .env && "${1:-}" != "--force" ]]; then
  echo ".env already exists - leaving it untouched (use --force to regenerate)."
  exit 0
fi
command -v openssl >/dev/null || { echo "openssl is required"; exit 1; }

umask 077
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

openssl genrsa -out "$tmp/private.pem" 2048 2>/dev/null
openssl pkcs8 -topk8 -nocrypt -in "$tmp/private.pem" -out "$tmp/private_pkcs8.pem"
openssl rsa -in "$tmp/private.pem" -pubout -out "$tmp/public.pem" 2>/dev/null

b64file() { base64 < "$1" | tr -d '\n'; }
key32()   { openssl rand -base64 32 | tr -d '\n'; }
# alphanumeric only, so the value is safe inside URLs / shell / YAML without escaping
password() { openssl rand -base64 36 | tr -dc 'A-Za-z0-9' | cut -c1-24; }

ADMIN_PASSWORD="$(password)Aa1"

cat > .env <<ENV
# Generated by scripts/bootstrap-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). NEVER commit this file.

# ---- datastores ----
POSTGRES_USER=neobank
POSTGRES_PASSWORD=$(password)
MONGO_USER=neobank
MONGO_PASSWORD=$(password)

# ---- auth-service: JWT signing keypair (RS256) + PII encryption ----
JWT_KEY_ID=neobank-key-$(date -u +%Y%m%d)
JWT_PRIVATE_KEY_B64=$(b64file "$tmp/private_pkcs8.pem")
JWT_PUBLIC_KEY_B64=$(b64file "$tmp/public.pem")
PII_ENCRYPTION_KEY_B64=$(key32)
PII_BLIND_INDEX_KEY_B64=$(key32)

# ---- first admin account (created on first start only; change the password after logging in) ----
ADMIN_BOOTSTRAP_EMAIL=admin@neobank.local
ADMIN_BOOTSTRAP_PASSWORD=${ADMIN_PASSWORD}

# ---- observability ----
GRAFANA_ADMIN_USER=admin
GRAFANA_ADMIN_PASSWORD=$(password)
# Starts Grafana, Prometheus and Kafka UI too. Remove / empty it for a leaner stack.
COMPOSE_PROFILES=observability

# ---- misc ----
CORS_ALLOWED_ORIGINS=http://localhost:3000,http://localhost:5173
SWAGGER_UI_ENABLED=true
LOG_FORMAT=ecs
ENV

echo "Wrote .env"
echo "  Admin login:  admin@neobank.local / ${ADMIN_PASSWORD}"
echo "  Next:         docker compose up --build"
